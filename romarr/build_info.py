"""Build provenance for diagnostics, independent of update eligibility.

Docker images generated by official CI carry an optional ``_build_info.py``.
A legacy image or plain source checkout may not have it; report unknown
rather than assume its Git revision, release tag, or repository.
"""
from __future__ import annotations

import re

from .version import is_unknown

_SHA = re.compile(r"[0-9a-f]{40}\Z")
_REPO = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+\Z")
_FIELDS = (
    "romarr_build_kind", "romarr_source_ref",
    "romarr_source_revision", "romarr_source_repository",
)


def _generated() -> dict[str, str]:
    """Read optional build-generated identity fields without guessing defaults."""
    try:
        from . import _build_info
    except ImportError:
        return {}
    return {field: getattr(_build_info, field, "") for field in _FIELDS}


def get_build_info(running_version: object) -> dict[str, object]:
    """Return validated provenance; never guess from a moving Docker tag.

    ``version_known`` only means the normal version resolver knows a version.
    It does *not* authorize auto-updating a development image.
    """
    known = not is_unknown(running_version)
    unknown: dict[str, object] = {
        "type": "unknown",
        "source_ref": "",
        "source_revision": "",
        "source_repository": "",
        "version_known": known,
    }
    raw = _generated()
    kind = str(raw.get("romarr_build_kind") or "").strip().lower()
    ref = str(raw.get("romarr_source_ref") or "").strip()
    revision = str(raw.get("romarr_source_revision") or "").strip().lower()
    repository = str(raw.get("romarr_source_repository") or "").strip()

    if kind not in ("release", "development"):
        return unknown
    if not _SHA.fullmatch(revision) or not _REPO.fullmatch(repository):
        return unknown
    if not ref or len(ref) > 250 or any(c.isspace() for c in ref):
        return unknown

    if kind == "release":
        if not ref.startswith("refs/tags/") or not known:
            return unknown
        tag = ref[len("refs/tags/"):]
        if tag.lstrip("vV") != str(running_version).strip().lstrip("vV"):
            return unknown
    elif ref.startswith("refs/heads/"):
        branch = ref[len("refs/heads/"):]
        if not branch or branch.startswith("/") or branch.endswith("/") or "//" in branch:
            return unknown
    elif not re.fullmatch(r"refs/pull/[1-9][0-9]*/(?:head|merge)", ref):
        return unknown

    return {
        "type": kind,
        "source_ref": ref,
        "source_revision": revision,
        "source_repository": repository,
        "version_known": known,
    }
